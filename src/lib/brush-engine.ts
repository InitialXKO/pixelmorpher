/** Render a plate / panel stroke with thickness and edge bevel.
 *  Creates a thick plate with visible side edges, beveled corners,
 *  and directional lighting for a solid 3D panel appearance. */
function renderPlateStroke(
  points: { x: number; y: number }[],
  size: number,
  color: string,
  params: BrushStyleParams,
  rng: () => number,
): BrushPixel[] {
  if (points.length === 0) return [];
  if (points.length === 1) {
    const stamp = renderPlateCrossSection(size, color, params, rng);
    return stamp.map(p => ({ ...p, x: p.x + Math.round(points[0].x), y: p.y + Math.round(points[0].y) }));
  }

  const arcLengths = computeArcLengths(points);
  const totalLen = arcLengths[arcLengths.length - 1];
  if (totalLen < 0.5) {
    const stamp = renderPlateCrossSection(size, color, params, rng);
    return stamp.map(p => ({ ...p, x: p.x + Math.round(points[0].x), y: p.y + Math.round(points[0].y) }));
  }

  const result: BrushPixel[] = [];
  const pixelMap = new Map<string, { color: string; opacity: number }>();
  const colorRGB = hexToRGB(color);

  const lightRad = (params.plateLightDir * Math.PI) / 180;
  const halfSize = size / 2;
  const thicknessHalf = halfSize * params.plateThickness;
  const bevelSize = thicknessHalf * params.plateBevel;

  const stepSize = 0.5;
  const numSamples = Math.max(2, Math.ceil(totalLen / stepSize) + 1);

  for (let i = 0; i < numSamples; i++) {
    const t = i / (numSamples - 1);
    const { x, y, tangentAngle } = interpolatePoint(points, arcLengths, t);
    const perpX = -Math.sin(tangentAngle);
    const perpY = Math.cos(tangentAngle);
    const lightPerpSign = Math.cos(lightRad - tangentAngle);

    const numCrossPixels = Math.ceil(size);
    for (let j = 0; j < numCrossPixels; j++) {
      const offset = -halfSize + (j / Math.max(1, numCrossPixels - 1)) * size;
      const px = Math.round(x + perpX * offset);
      const py = Math.round(y + perpY * offset);
      const absOff = Math.abs(offset);

      let shadeColor: RGB;
      let localOpacity = 1;

      // Surface texture noise
      const texNoise = params.surfaceTexture > 0
        ? (rng() - 0.5) * params.surfaceTexture * 0.3
        : 0;

      if (absOff <= thicknessHalf - bevelSize) {
        // Main flat surface
        const surfBright = 0.85 + texNoise;
        shadeColor = {
          r: Math.min(255, colorRGB.r * surfBright),
          g: Math.min(255, colorRGB.g * surfBright),
          b: Math.min(255, colorRGB.b * surfBright),
        };
      } else if (absOff <= thicknessHalf) {
        // Bevel zone: transition from surface to side
        const bevelT = (absOff - (thicknessHalf - bevelSize)) / Math.max(0.01, bevelSize);
        const sideSign = offset > 0 ? 1 : -1;
        const lit = sideSign * lightPerpSign > 0;
        const sideBright = lit ? 0.7 : 0.35;
        const bevelBright = 0.85 * (1 - bevelT) + sideBright * bevelT + texNoise;
        shadeColor = {
          r: Math.min(255, Math.max(0, colorRGB.r * bevelBright)),
          g: Math.min(255, Math.max(0, colorRGB.g * bevelBright)),
          b: Math.min(255, Math.max(0, colorRGB.b * bevelBright)),
        };
        // Edge highlight at the bevel peak
        if (params.plateEdgeBright > 0 && bevelT > 0.3 && bevelT < 0.7) {
          const edgeMix = (1 - Math.abs(bevelT - 0.5) * 4) * params.plateEdgeBright;
          shadeColor = lerpColor(shadeColor, { r: 255, g: 255, b: 255 }, Math.max(0, edgeMix));
        }
      } else if (absOff <= halfSize) {
        // Side face (visible thickness)
        const sideSign = offset > 0 ? 1 : -1;
        const lit = sideSign * lightPerpSign > 0;
        const depthFade = 1 - (absOff - thicknessHalf) / Math.max(0.01, halfSize - thicknessHalf);
        const sideBright = (lit ? 0.55 : 0.25) * depthFade;
        shadeColor = {
          r: colorRGB.r * sideBright,
          g: colorRGB.g * sideBright,
          b: colorRGB.b * sideBright,
        };
      } else {
        continue;
      }

      const edgeDist = halfSize - absOff;
      const softEdge = 1 - params.hardness;
      const edgeWidth = Math.max(0.01, softEdge * halfSize);
      localOpacity = edgeDist < edgeWidth ? edgeDist / edgeWidth : 1;

      if (localOpacity > 0.01) {
        const key = `${px},${py}`;
        const existing = pixelMap.get(key);
        if (!existing || existing.opacity < localOpacity * params.opacity) {
          pixelMap.set(key, {
            color: rgbToHex(shadeColor.r, shadeColor.g, shadeColor.b),
            opacity: localOpacity * params.opacity,
          });
        }
      }
    }
  }

  for (const [key, val] of pixelMap) {
    const [xStr, yStr] = key.split(',');
    result.push({ x: parseInt(xStr), y: parseInt(yStr), color: val.color, opacity: val.opacity });
  }
  return result;
}

