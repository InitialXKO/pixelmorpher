/** Render a bevel seam / groove stroke with directional lighting.
 *  Creates a recessed groove with highlight on one edge and shadow on the other,
 *  simulating a chamfered seam or joint line. */
function renderBevelSeamStroke(
  points: { x: number; y: number }[],
  size: number,
  color: string,
  params: BrushStyleParams,
  rng: () => number,
): BrushPixel[] {
  if (points.length === 0) return [];
  if (points.length === 1) {
    const stamp = renderBevelSeamCrossSection(size, color, params);
    return stamp.map(p => ({ ...p, x: p.x + Math.round(points[0].x), y: p.y + Math.round(points[0].y) }));
  }

  const arcLengths = computeArcLengths(points);
  const totalLen = arcLengths[arcLengths.length - 1];
  if (totalLen < 0.5) {
    const stamp = renderBevelSeamCrossSection(size, color, params);
    return stamp.map(p => ({ ...p, x: p.x + Math.round(points[0].x), y: p.y + Math.round(points[0].y) }));
  }

  const result: BrushPixel[] = [];
  const pixelMap = new Map<string, { color: string; opacity: number }>();
  const colorRGB = hexToRGB(color);
  const grooveRGB = hexToRGB(params.grooveColor);

  const lightRad = (params.bevelLightDir * Math.PI) / 180;
  const stepSize = 0.5;
  const numSamples = Math.max(2, Math.ceil(totalLen / stepSize) + 1);

  for (let i = 0; i < numSamples; i++) {
    const t = i / (numSamples - 1);
    const { x, y, tangentAngle } = interpolatePoint(points, arcLengths, t);
    const perpX = -Math.sin(tangentAngle);
    const perpY = Math.cos(tangentAngle);

    const halfSize = size / 2;
    const bevelBand = halfSize * params.bevelWidth;
    const grooveHalf = halfSize * (1 - params.bevelWidth) * params.bevelDepth;

    // Light direction in perpendicular space: project light angle onto perpendicular
    const lightPerpSign = Math.cos(lightRad - tangentAngle);
    // Positive = light from one side, negative = from the other

    const numCrossPixels = Math.ceil(size);
    for (let j = 0; j < numCrossPixels; j++) {
      const offset = -halfSize + (j / Math.max(1, numCrossPixels - 1)) * size;
      const px = Math.round(x + perpX * offset);
      const py = Math.round(y + perpY * offset);
      const absOff = Math.abs(offset);

      let shadeColor: RGB;
      let localOpacity = 1;

      if (absOff > halfSize - bevelBand) {
        // Bevel highlight/shadow edge zone
        const edgeT = (absOff - (halfSize - bevelBand)) / Math.max(0.01, bevelBand);
        const sideSign = offset > 0 ? 1 : -1;
        const lit = sideSign * lightPerpSign > 0; // this side faces the light
        if (lit) {
          // Highlight edge: bright
          const highlightMix = edgeT * (1 - params.bevelShadow * 0.5);
          shadeColor = lerpColor(colorRGB, { r: 255, g: 255, b: 255 }, highlightMix * 0.4);
        } else {
          // Shadow edge: dark
          const shadowMix = edgeT * params.bevelShadow;
          shadeColor = lerpColor(colorRGB, grooveRGB, shadowMix);
        }
      } else if (absOff < grooveHalf) {
        // Groove interior: dark
        const grooveT = absOff / Math.max(0.01, grooveHalf);
        const centerDark = (1 - grooveT) * params.bevelShadow;
        shadeColor = lerpColor(colorRGB, grooveRGB, centerDark);
      } else {
        // Main surface: subtle directional shading
        const normalOff = offset / halfSize;
        const shadeFactor = 0.5 + 0.5 * normalOff * lightPerpSign;
        shadeColor = {
          r: colorRGB.r * shadeFactor,
          g: colorRGB.g * shadeFactor,
          b: colorRGB.b * shadeFactor,
        };
      }

      // Edge falloff
      const edgeDist = halfSize - absOff;
      const softEdge = 1 - params.hardness;
      const edgeWidth = Math.max(0.01, softEdge * halfSize);
      localOpacity = edgeDist < edgeWidth ? edgeDist / edgeWidth : 1;

      if (localOpacity > 0.01) {
        const key = `${px},${py}`;
        pixelMap.set(key, {
          color: rgbToHex(shadeColor.r, shadeColor.g, shadeColor.b),
          opacity: localOpacity * params.opacity,
        });
      }
    }
  }

  for (const [key, val] of pixelMap) {
    const [xStr, yStr] = key.split(',');
    result.push({ x: parseInt(xStr), y: parseInt(yStr), color: val.color, opacity: val.opacity });
  }
  return result;
}

/** Cross-section preview for bevel seam */
function renderBevelSeamCrossSection(
  size: number,
  color: string,
  params: BrushStyleParams,
): BrushPixel[] {
  const pixels: BrushPixel[] = [];
  const halfSize = size / 2;
  const colorRGB = hexToRGB(color);
  const grooveRGB = hexToRGB(params.grooveColor);

  for (let dy = -Math.ceil(halfSize); dy < Math.floor(halfSize + 0.5); dy++) {
    for (let dx = -Math.ceil(halfSize); dx < Math.floor(halfSize + 0.5); dx++) {
      const dist = Math.sqrt(dx * dx + dy * dy);
      if (dist > halfSize) continue;
      const normalDist = dist / halfSize;
      const bevelBand = params.bevelWidth;
      let shadeColor: RGB;

      if (normalDist > 1 - bevelBand) {
        // Edge highlight
        const edgeT = (normalDist - (1 - bevelBand)) / Math.max(0.01, bevelBand);
        shadeColor = lerpColor(colorRGB, { r: 255, g: 255, b: 255 }, edgeT * 0.3);
      } else if (normalDist < params.bevelDepth * 0.3) {
        // Groove center
        shadeColor = lerpColor(colorRGB, grooveRGB, params.bevelShadow);
      } else {
        shadeColor = colorRGB;
      }

      const edgeDist = halfSize - dist;
      const softEdge = 1 - params.hardness;
      const edgeWidth = Math.max(0.01, softEdge * halfSize);
      const opacity = edgeDist < edgeWidth ? edgeDist / edgeWidth : 1;

      if (opacity > 0.01) {
        pixels.push({
          x: dx, y: dy,
          color: rgbToHex(shadeColor.r, shadeColor.g, shadeColor.b),
          opacity: opacity * params.opacity,
        });
      }
    }
  }
  return pixels;
}

/** Render a prism / frustum stroke with directional lighting.
 *  Creates a 3D prism effect with a visible top face and angled sides,
 *  where topWidthRatio < 1 produces a trapezoidal (frustum) cross-section. */
function renderPrismStroke(
  points: { x: number; y: number }[],
  size: number,
  color: string,
  params: BrushStyleParams,
  rng: () => number,
): BrushPixel[] {
  if (points.length === 0) return [];
  if (points.length === 1) {
    const stamp = renderPrismCrossSection(size, color, params);
    return stamp.map(p => ({ ...p, x: p.x + Math.round(points[0].x), y: p.y + Math.round(points[0].y) }));
  }

  const arcLengths = computeArcLengths(points);
  const totalLen = arcLengths[arcLengths.length - 1];
  if (totalLen < 0.5) {
    const stamp = renderPrismCrossSection(size, color, params);
    return stamp.map(p => ({ ...p, x: p.x + Math.round(points[0].x), y: p.y + Math.round(points[0].y) }));
  }

  const result: BrushPixel[] = [];
  const pixelMap = new Map<string, { color: string; opacity: number }>();
  const colorRGB = hexToRGB(color);

  const lightRad = (params.prismLightDir * Math.PI) / 180;
  const halfSize = size / 2;
  const topHalf = halfSize * params.topWidthRatio;
  const bodyH = halfSize * params.prismHeight;

  const stepSize = 0.5;
  const numSamples = Math.max(2, Math.ceil(totalLen / stepSize) + 1);

  for (let i = 0; i < numSamples; i++) {
    const t = i / (numSamples - 1);
    const { x, y, tangentAngle } = interpolatePoint(points, arcLengths, t);
    const perpX = -Math.sin(tangentAngle);
    const perpY = Math.cos(tangentAngle);

    const lightPerpSign = Math.cos(lightRad - tangentAngle);

    const numCrossPixels = Math.ceil(size);
    for (let j = 0; j < numCrossPixels; j++) {
      const offset = -halfSize + (j / Math.max(1, numCrossPixels - 1)) * size;
      const px = Math.round(x + perpX * offset);
      const py = Math.round(y + perpY * offset);
      const absOff = Math.abs(offset);

      let shadeColor: RGB;
      let localOpacity = 1;

      if (absOff <= topHalf) {
        // Top face — brighter
        const topBright = 0.7 + 0.3 * params.topFaceBrightness;
        shadeColor = {
          r: Math.min(255, colorRGB.r * topBright),
          g: Math.min(255, colorRGB.g * topBright),
          b: Math.min(255, colorRGB.b * topBright),
        };
      } else if (absOff <= halfSize) {
        // Angled side face
        const sideT = (absOff - topHalf) / Math.max(0.01, halfSize - topHalf);
        const sideSign = offset > 0 ? 1 : -1;
        const lit = sideSign * lightPerpSign > 0;
        const sideShade = lit ? (0.6 + 0.3 * (1 - sideT)) : (0.3 + 0.2 * (1 - sideT));
        shadeColor = {
          r: colorRGB.r * sideShade,
          g: colorRGB.g * sideShade,
          b: colorRGB.b * sideShade,
        };

        // Edge highlight at the boundary between top and side
        if (sideT < 0.15 && params.edgeHighlight > 0) {
          shadeColor = lerpColor(shadeColor, { r: 255, g: 255, b: 255 }, params.edgeHighlight * (1 - sideT / 0.15));
        }
      } else {
        continue;
      }

      const edgeDist = halfSize - absOff;
      const softEdge = 1 - params.hardness;
      const edgeWidth = Math.max(0.01, softEdge * halfSize);
      localOpacity = edgeDist < edgeWidth ? edgeDist / edgeWidth : 1;

      if (localOpacity > 0.01) {
        const key = `${px},${py}`;
        pixelMap.set(key, {
          color: rgbToHex(shadeColor.r, shadeColor.g, shadeColor.b),
          opacity: localOpacity * params.opacity,
        });
      }
    }
  }

  for (const [key, val] of pixelMap) {
    const [xStr, yStr] = key.split(',');
    result.push({ x: parseInt(xStr), y: parseInt(yStr), color: val.color, opacity: val.opacity });
  }
  return result;
}

