// ---- Seeded PRNG (mulberry32) ----

function mulberry32(seed: number): () => number {
  let s = seed | 0;
  return () => {
    s = (s + 0x6d2b79f5) | 0;
    let t = Math.imul(s ^ (s >>> 15), 1 | s);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// ---- Color Utilities ----

interface RGB { r: number; g: number; b: number; }

function hexToRGB(hex: string): RGB {
  const h = hex.replace('#', '');
  return {
    r: parseInt(h.slice(0, 2), 16),
    g: parseInt(h.slice(2, 4), 16),
    b: parseInt(h.slice(4, 6), 16),
  };
}

function lerpColor(c1: RGB, c2: RGB, t: number): RGB {
  return {
    r: c1.r + (c2.r - c1.r) * t,
    g: c1.g + (c2.g - c1.g) * t,
    b: c1.b + (c2.b - c1.b) * t,
  };
}

function blendWithBackground(bg: PixelColor, fg: RGB, opacity: number): PixelColor {
  if (bg === null) {
    // Blend with transparent = just apply opacity
    return opacity < 0.01 ? null : rgbToHex(fg.r * opacity, fg.g * opacity, fg.b * opacity);
  }
  const bgRGB = hexToRGB(bg);
  const a = opacity;
  return rgbToHex(
    bgRGB.r * (1 - a) + fg.r * a,
    bgRGB.g * (1 - a) + fg.g * a,
    bgRGB.b * (1 - a) + fg.b * a,
  );
}

// ---- Brush Stamp Output ----

/** A single pixel generated by a brush stamp */
export interface BrushPixel {
  x: number;       // offset from stamp center (or absolute for stroke-aware)
  y: number;       // offset from stamp center (or absolute for stroke-aware)
  color: string;   // hex color (always non-null)
  opacity: number; // 0-1 blend factor
}

// ---- Smoothstep utility ----

function smoothstep(edge0: number, edge1: number, x: number): number {
  const t = Math.max(0, Math.min(1, (x - edge0) / (edge1 - edge0)));
  return t * t * (3 - 2 * t);
}

// ---- Stroke Geometry Helpers ----

/** Compute cumulative arc-length distances along a polyline path */
function computeArcLengths(points: { x: number; y: number }[]): number[] {
  const lengths: number[] = [0];
  for (let i = 1; i < points.length; i++) {
    const dx = points[i].x - points[i - 1].x;
    const dy = points[i].y - points[i - 1].y;
    lengths.push(lengths[i - 1] + Math.sqrt(dx * dx + dy * dy));
  }
  return lengths;
}

/** Interpolate a point along the path at normalized position t (0–1) */
function interpolatePoint(
  points: { x: number; y: number }[],
  arcLengths: number[],
  t: number,
): { x: number; y: number; tangentAngle: number } {
  const totalLen = arcLengths[arcLengths.length - 1] || 0;
  if (totalLen === 0) return { x: points[0]?.x ?? 0, y: points[0]?.y ?? 0, tangentAngle: 0 };

  const targetLen = t * totalLen;

  // Find the segment containing targetLen
  let segIdx = 0;
  for (let i = 1; i < arcLengths.length; i++) {
    if (arcLengths[i] >= targetLen) { segIdx = i - 1; break; }
    if (i === arcLengths.length - 1) segIdx = i - 1;
  }

  const segStart = arcLengths[segIdx];
  const segEnd = arcLengths[segIdx + 1] ?? segStart;
  const segFrac = segEnd > segStart ? (targetLen - segStart) / (segEnd - segStart) : 0;

  const p0 = points[segIdx];
  const p1 = points[segIdx + 1] ?? p0;

  const x = p0.x + (p1.x - p0.x) * segFrac;
  const y = p0.y + (p1.y - p0.y) * segFrac;
  const tangentAngle = Math.atan2(p1.y - p0.y, p1.x - p0.x);

  return { x, y, tangentAngle };
}

/** Compute taper size factor at normalized position t along the stroke */
function taperFactor(t: number, taperLength: number, taperCurve: string, minSizeRatio: number): number {
  if (taperLength <= 0) return 1;

  // Factor for start taper (t near 0)
  const startT = t / taperLength;
  let startFactor = 1;
  if (startT < 1) {
    const clamped = Math.max(0, Math.min(1, startT));
    switch (taperCurve) {
      case 'linear': startFactor = clamped; break;
      case 'ease_in': startFactor = clamped * clamped; break;
      case 'ease_out': startFactor = 1 - (1 - clamped) * (1 - clamped); break;
      case 'smooth': default: startFactor = smoothstep(0, 1, clamped); break;
    }
  }

  // Factor for end taper (t near 1)
  const endT = (1 - t) / taperLength;
  let endFactor = 1;
  if (endT < 1) {
    const clamped = Math.max(0, Math.min(1, endT));
    switch (taperCurve) {
      case 'linear': endFactor = clamped; break;
      case 'ease_in': endFactor = clamped * clamped; break;
      case 'ease_out': endFactor = 1 - (1 - clamped) * (1 - clamped); break;
      case 'smooth': default: endFactor = smoothstep(0, 1, clamped); break;
    }
  }

  // Combined: both tapers apply; interpolate from minSizeRatio to 1
  const factor = Math.min(startFactor, endFactor);
  return minSizeRatio + (1 - minSizeRatio) * factor;
}

/** Check if a style requires the full stroke path */
export function isStrokeAwareStyle(style: BrushStyleType): boolean {
  return (STROKE_AWARE_STYLES as string[]).includes(style);
}

// ---- Stamp-based Style Renderers (unchanged from V5) ----

/** Render a solid brush stamp: all pixels within radius get the same color */
function renderSolid(
  size: number,
  color: string,
  params: BrushStyleParams,
): BrushPixel[] {
  const pixels: BrushPixel[] = [];
  const halfSize = size / 2;
  const colorRGB = hexToRGB(color);

  for (let dy = -Math.ceil(halfSize); dy < Math.floor(halfSize + 0.5); dy++) {
    for (let dx = -Math.ceil(halfSize); dx < Math.floor(halfSize + 0.5); dx++) {
      const dist = Math.sqrt(dx * dx + dy * dy);
      const maxDist = halfSize;

      if (dist <= maxDist) {
        const edgeDist = maxDist - dist;
        const hardness = params.hardness;
        const softEdge = 1 - hardness;
        const edgeWidth = Math.max(0.01, softEdge * maxDist);
        const opacity = edgeDist < edgeWidth ? edgeDist / edgeWidth : 1;

        if (opacity > 0.01) {
          pixels.push({
            x: dx, y: dy,
            color: rgbToHex(colorRGB.r, colorRGB.g, colorRGB.b),
            opacity: opacity * params.opacity,
          });
        }
      }
    }
  }

  return pixels;
}

/** Render a glow orb: radial gradient from innerColor (center) to outerColor (edge) */
function renderGlowOrb(
  size: number,
  color: string,
  params: BrushStyleParams,
  rng: () => number,
): BrushPixel[] {
  const pixels: BrushPixel[] = [];
  const halfSize = size / 2;
  const innerRGB = hexToRGB(params.innerColor);
  const outerRGB = hexToRGB(params.outerColor);
  const innerRadius = params.innerRadius;

  for (let dy = -Math.ceil(halfSize); dy < Math.floor(halfSize + 0.5); dy++) {
    for (let dx = -Math.ceil(halfSize); dx < Math.floor(halfSize + 0.5); dx++) {
      const dist = Math.sqrt(dx * dx + dy * dy);
      const maxDist = halfSize;

      if (dist <= maxDist) {
        const normalizedDist = dist / maxDist;

        const innerEdge = innerRadius;
        const falloff = params.falloff;
        const colorT = smoothstep(innerEdge - falloff * 0.5, innerEdge + falloff * 0.5, normalizedDist);
        const blended = lerpColor(innerRGB, outerRGB, colorT);

        const edgeDist = maxDist - dist;
        const softEdge = 1 - params.hardness;
        const edgeWidth = Math.max(0.01, softEdge * maxDist);
        const opacity = edgeDist < edgeWidth ? edgeDist / edgeWidth : 1;

        if (opacity > 0.01) {
          pixels.push({
            x: dx, y: dy,
            color: rgbToHex(blended.r, blended.g, blended.b),
            opacity: opacity * params.opacity,
          });
        }
      }
    }
  }

  return pixels;
}

/** Render a dual-color flame: elongated glow with inner/outer colors and flicker */
function renderDualFlame(
  size: number,
  color: string,
  params: BrushStyleParams,
  rng: () => number,
): BrushPixel[] {
  const pixels: BrushPixel[] = [];
  const halfSize = size / 2;
  const innerRGB = hexToRGB(params.innerColor);
  const outerRGB = hexToRGB(params.outerColor);
  const innerRadius = params.innerRadius;
  const elongation = params.elongation;

  const flameAngleRad = (params.flameDirection * Math.PI) / 180;
  const dirX = Math.cos(flameAngleRad);
  const dirY = Math.sin(flameAngleRad);
  const perpX = -dirY;
  const perpY = dirX;

  const flickerOffset = (rng() - 0.5) * 2 * params.flickerAmount * halfSize * 0.3;

  for (let dy = -Math.ceil(halfSize * elongation); dy <= Math.ceil(halfSize * elongation); dy++) {
    for (let dx = -Math.ceil(halfSize * elongation); dx <= Math.ceil(halfSize * elongation); dx++) {
      const alongFlame = dx * dirX + dy * dirY + flickerOffset;
      const acrossFlame = dx * perpX + dy * perpY;

      const normalAlong = alongFlame / (halfSize * elongation);
      const normalAcross = acrossFlame / halfSize;
      const ellipticalDist = Math.sqrt(normalAlong * normalAlong + normalAcross * normalAcross);

      if (ellipticalDist <= 1) {
        const normalizedDist = ellipticalDist;

        const colorT = smoothstep(
          innerRadius - params.falloff * 0.5,
          innerRadius + params.falloff * 0.5,
          normalizedDist,
        );
        const blended = lerpColor(innerRGB, outerRGB, colorT);

        const edgeDist = 1 - normalizedDist;
        const softEdge = 1 - params.hardness;
        const edgeWidth = Math.max(0.01, softEdge);
        const opacity = edgeDist < edgeWidth ? edgeDist / edgeWidth : 1;

        const brightBoost = normalizedDist < innerRadius * 0.5
          ? 1 + (1 - normalizedDist / (innerRadius * 0.5)) * 0.3
          : 1;
        const finalColor = rgbToHex(
          Math.min(255, blended.r * brightBoost),
          Math.min(255, blended.g * brightBoost),
          Math.min(255, blended.b * brightBoost),
        );

        if (opacity > 0.01) {
          pixels.push({
            x: dx, y: dy,
            color: finalColor,
            opacity: opacity * params.opacity,
          });
        }
      }
    }
  }

  return pixels;
}

/** Render a spray brush: scattered random dots within the brush radius */
function renderSpray(
  size: number,
  color: string,
  params: BrushStyleParams,
  rng: () => number,
): BrushPixel[] {
  const pixels: BrushPixel[] = [];
  const halfSize = size / 2 * params.spread;
  const colorRGB = hexToRGB(color);

  const area = Math.PI * halfSize * halfSize;
  const numParticles = Math.max(1, Math.floor(area * params.density * 0.3));

  for (let i = 0; i < numParticles; i++) {
    const angle = rng() * Math.PI * 2;
    const radius = Math.sqrt(rng()) * halfSize;
    const px = Math.round(Math.cos(angle) * radius);
    const py = Math.round(Math.sin(angle) * radius);

    const particleOpacity = (0.3 + rng() * 0.7) * params.opacity;

    pixels.push({
      x: px, y: py,
      color: rgbToHex(colorRGB.r, colorRGB.g, colorRGB.b),
      opacity: particleOpacity,
    });
  }

  return pixels;
}

/** Render a neon brush: bright center line with glow halo */
function renderNeon(
  size: number,
  color: string,
  params: BrushStyleParams,
  rng: () => number,
): BrushPixel[] {
  const pixels: BrushPixel[] = [];
  const colorRGB = hexToRGB(color);
  const glowRadius = params.glowRadius;
  const totalRadius = Math.ceil(size / 2) + glowRadius;

  for (let dy = -totalRadius; dy <= totalRadius; dy++) {
    for (let dx = -totalRadius; dx <= totalRadius; dx++) {
      const dist = Math.sqrt(dx * dx + dy * dy);
      const coreRadius = size / 2;

      if (dist <= totalRadius) {
        let opacity: number;
        let finalColor: RGB;

        if (dist <= coreRadius) {
          const coreBright = 1 + params.glowIntensity * 0.5;
          finalColor = {
            r: Math.min(255, colorRGB.r * coreBright + (255 - colorRGB.r) * params.glowIntensity * 0.3),
            g: Math.min(255, colorRGB.g * coreBright + (255 - colorRGB.g) * params.glowIntensity * 0.3),
            b: Math.min(255, colorRGB.b * coreBright + (255 - colorRGB.b) * params.glowIntensity * 0.3),
          };
          const edgeDist = coreRadius - dist;
          const softEdge = 1 - params.hardness;
          const edgeWidth = Math.max(0.01, softEdge * coreRadius);
          opacity = edgeDist < edgeWidth ? edgeDist / edgeWidth : 1;
        } else {
          const glowDist = dist - coreRadius;
          const glowFalloff = glowRadius > 0 ? glowDist / glowRadius : 1;
          if (glowFalloff > 1) continue;
          opacity = (1 - glowFalloff) * params.glowIntensity;
          finalColor = { ...colorRGB };
        }

        if (opacity > 0.01) {
          pixels.push({
            x: dx, y: dy,
            color: rgbToHex(finalColor.r, finalColor.g, finalColor.b),
            opacity: opacity * params.opacity,
          });
        }
      }
    }
  }

  return pixels;
}

/** Render a gradient brush: linear or radial gradient fill */
function renderGradient(
  size: number,
  color: string,
  params: BrushStyleParams,
  rng: () => number,
): BrushPixel[] {
  const pixels: BrushPixel[] = [];
  const halfSize = size / 2;
  const primaryRGB = hexToRGB(color);
  const secondaryRGB = hexToRGB(params.secondaryColor);

  for (let dy = -Math.ceil(halfSize); dy < Math.floor(halfSize + 0.5); dy++) {
    for (let dx = -Math.ceil(halfSize); dx < Math.floor(halfSize + 0.5); dx++) {
      const dist = Math.sqrt(dx * dx + dy * dy);
      const maxDist = halfSize;

      if (dist <= maxDist) {
        let gradientT: number;

        if (params.gradientType === 'radial') {
          gradientT = dist / maxDist;
        } else {
          gradientT = (dx + halfSize) / (2 * halfSize);
        }

        const blended = lerpColor(primaryRGB, secondaryRGB, gradientT);

        const edgeDist = maxDist - dist;
        const softEdge = 1 - params.hardness;
        const edgeWidth = Math.max(0.01, softEdge * maxDist);
        const opacity = edgeDist < edgeWidth ? edgeDist / edgeWidth : 1;

        if (opacity > 0.01) {
          pixels.push({
            x: dx, y: dy,
            color: rgbToHex(blended.r, blended.g, blended.b),
            opacity: opacity * params.opacity,
          });
        }
      }
    }
  }

  return pixels;
}

/** Render a scatter brush: random placement of the brush shape stamp within radius */
function renderScatter(
  size: number,
  color: string,
  params: BrushStyleParams,
  rng: () => number,
): BrushPixel[] {
  const pixels: BrushPixel[] = [];
  const halfSize = size / 2 * params.spread;
  const colorRGB = hexToRGB(color);

  const numStamps = Math.max(1, Math.floor(params.density * 8));

  for (let s = 0; s < numStamps; s++) {
    const angle = rng() * Math.PI * 2;
    const radius = Math.sqrt(rng()) * halfSize;
    const cx = Math.round(Math.cos(angle) * radius);
    const cy = Math.round(Math.sin(angle) * radius);

    const stampRadius = Math.max(1, Math.floor(size / 4));
    const stampOpacity = (0.4 + rng() * 0.6) * params.opacity;

    for (let dy = -stampRadius; dy <= stampRadius; dy++) {
      for (let dx = -stampRadius; dx <= stampRadius; dx++) {
        if (dx * dx + dy * dy <= stampRadius * stampRadius) {
          pixels.push({
            x: cx + dx, y: cy + dy,
            color: rgbToHex(colorRGB.r, colorRGB.g, colorRGB.b),
            opacity: stampOpacity,
          });
        }
      }
    }
  }

  return pixels;
}

// ---- V8: Shape Stamp Renderers (star, heart, sphere, droplet, bubble, punctuation, emoji) ----

/** Render a star shape: multi-pointed star with inner/outer color and hollow option */
function renderStar(
  size: number,
  color: string,
  params: BrushStyleParams,
  rng: () => number,
): BrushPixel[] {
  const pixels: BrushPixel[] = [];
  const halfSize = size / 2;
  const spikeCount = Math.max(3, Math.round(params.spikeCount));
  const innerRatio = params.innerOuterRatio;
  const rotationRad = (params.rotation * Math.PI) / 180;
  const innerRGB = hexToRGB(params.innerColor);
  const outerRGB = hexToRGB(params.outerColor);

  for (let dy = -Math.ceil(halfSize); dy <= Math.ceil(halfSize); dy++) {
    for (let dx = -Math.ceil(halfSize); dx <= Math.ceil(halfSize); dx++) {
      const dist = Math.sqrt(dx * dx + dy * dy);
      if (dist > halfSize + 0.5) continue;

      const angle = Math.atan2(dy, dx) - rotationRad;
      // Determine which star sector this pixel is in
      const sectorAngle = (2 * Math.PI) / spikeCount;
      const halfSector = sectorAngle / 2;
      let normalizedAngle = ((angle % sectorAngle) + sectorAngle) % sectorAngle;
      // Distance from center to the star edge at this angle
      const t = normalizedAngle / sectorAngle; // 0 to 1 within sector
      // Interpolate between outer radius (at tip) and inner radius (at valley)
      const edgeDist = halfSize * (t < 0.5
        ? innerRatio + (1 - innerRatio) * (1 - t * 2)
        : innerRatio + (1 - innerRatio) * ((t - 0.5) * 2));

      if (params.hollow) {
        // Hollow: only ring between inner and outer
        const innerEdge = edgeDist * innerRatio;
        const thickness = Math.max(1, halfSize * 0.15);
        if (dist >= edgeDist - thickness && dist <= edgeDist) {
          const colorT = dist / halfSize;
          const blended = lerpColor(outerRGB, innerRGB, 1 - colorT);
          const edgeDistFromOuter = edgeDist - dist;
          const softEdge = 1 - params.hardness;
          const edgeWidth = Math.max(0.01, softEdge * thickness);
          const opacity = Math.min(
            edgeDistFromOuter < edgeWidth ? edgeDistFromOuter / edgeWidth : 1,
            dist > edgeDist - thickness ? 1 : (dist - (edgeDist - thickness)) / Math.max(0.01, thickness * 0.3),
          );
          if (opacity > 0.01) {
            pixels.push({ x: dx, y: dy, color: rgbToHex(blended.r, blended.g, blended.b), opacity: opacity * params.opacity });
          }
        }
      } else {
        // Solid: fill inside the star shape
        if (dist <= edgeDist) {
          const colorT = dist / edgeDist;
          const blended = lerpColor(innerRGB, outerRGB, colorT);
          const edgeDistFromOuter = edgeDist - dist;
          const softEdge = 1 - params.hardness;
          const edgeWidth = Math.max(0.01, softEdge * edgeDist * 0.3);
          const opacity = edgeDistFromOuter < edgeWidth ? edgeDistFromOuter / edgeWidth : 1;
          if (opacity > 0.01) {
            pixels.push({ x: dx, y: dy, color: rgbToHex(blended.r, blended.g, blended.b), opacity: opacity * params.opacity });
          }
        }
      }
    }
  }
  return pixels;
}

/** Render a heart shape: cardioid with inner/outer color gradient */
function renderHeart(
  size: number,
  color: string,
  params: BrushStyleParams,
  rng: () => number,
): BrushPixel[] {
  const pixels: BrushPixel[] = [];
  const halfSize = size / 2;
  const innerRGB = hexToRGB(params.innerColor);
  const outerRGB = hexToRGB(params.outerColor);
  const lobeW = params.lobeWidth;
  const pointy = params.pointiness;

  for (let dy = -Math.ceil(halfSize * 1.2); dy <= Math.ceil(halfSize); dy++) {
    for (let dx = -Math.ceil(halfSize * lobeW); dx <= Math.ceil(halfSize * lobeW); dx++) {
      // Normalize to -1..1 range
      const nx = dx / (halfSize * lobeW);
      const ny = -dy / halfSize; // flip y so +1 is top

      // Heart implicit surface: (x^2 + y^2 - 1)^3 - x^2 * y^3 < 0
      const x2 = nx * nx;
      const yShifted = ny - 0.2 + pointy * 0.15; // shift up to center the heart
      const y2 = yShifted * yShifted;
      const val = Math.pow(x2 + y2 - 1, 3) - x2 * Math.pow(yShifted, 3) * (1 + pointy * 0.5);

      if (val <= 0) {
        const dist = Math.sqrt(nx * nx + (ny + 0.3) * (ny + 0.3));
        const colorT = Math.min(1, dist / 1.2);
        const blended = lerpColor(innerRGB, outerRGB, colorT);

        // Edge softness based on how close val is to 0
        const edgeDist = -val;
        const softEdge = 1 - params.hardness;
        const edgeWidth = Math.max(0.01, softEdge * 0.3);
        const opacity = edgeDist < edgeWidth ? edgeDist / edgeWidth : 1;

        if (opacity > 0.01) {
          pixels.push({ x: dx, y: dy, color: rgbToHex(blended.r, blended.g, blended.b), opacity: opacity * params.opacity });
        }
      }
    }
  }
  return pixels;
}

/** Render a sphere: circular with configurable highlight position and shading */
function renderSphere(
  size: number,
  color: string,
  params: BrushStyleParams,
  rng: () => number,
): BrushPixel[] {
  const pixels: BrushPixel[] = [];
  const halfSize = size / 2;
  const colorRGB = hexToRGB(color);
  const hlX = params.highlightX;
  const hlY = params.highlightY;
  const hlRadius = params.highlightRadius;
  const hlBrightness = params.highlightBrightness;
  const shading = params.shadingIntensity;

  for (let dy = -Math.ceil(halfSize); dy <= Math.ceil(halfSize); dy++) {
    for (let dx = -Math.ceil(halfSize); dx <= Math.ceil(halfSize); dx++) {
      const dist = Math.sqrt(dx * dx + dy * dy);
      if (dist > halfSize + 0.5) continue;
      if (dist > halfSize) {
        // Anti-alias edge
        const edgeOp = 1 - (dist - halfSize);
        if (edgeOp > 0.01) {
          pixels.push({ x: dx, y: dy, color: rgbToHex(colorRGB.r * 0.3, colorRGB.g * 0.3, colorRGB.b * 0.3), opacity: edgeOp * params.opacity });
        }
        continue;
      }

      const nx = dx / halfSize; // -1 to 1
      const ny = dy / halfSize;

      // Sphere shading: darker at edges, lighter toward center-facing-light
      const normalZ = Math.sqrt(Math.max(0, 1 - nx * nx - ny * ny));
      // Light direction from highlight position (highlight is where light hits)
      const lightDirX = -hlX;
      const lightDirY = -hlY;
      const lightLen = Math.sqrt(lightDirX * lightDirX + lightDirY * lightDirY + 1);
      const dot = (nx * lightDirX + ny * lightDirY + normalZ) / lightLen;
      const diffuse = Math.max(0, dot);
      const shade = 1 - shading + shading * (0.3 + 0.7 * diffuse);

      // Specular highlight
      const distToHL = Math.sqrt((nx - hlX) * (nx - hlX) + (ny - hlY) * (ny - hlY));
      const specular = distToHL < hlRadius
        ? (1 - distToHL / hlRadius) * hlBrightness
        : 0;

      const r = Math.min(255, colorRGB.r * shade + specular * 255);
      const g = Math.min(255, colorRGB.g * shade + specular * 255);
      const b = Math.min(255, colorRGB.b * shade + specular * 255);

      const edgeDist = halfSize - dist;
      const softEdge = 1 - params.hardness;
      const edgeWidth = Math.max(0.01, softEdge * halfSize);
      const opacity = edgeDist < edgeWidth ? edgeDist / edgeWidth : 1;

      if (opacity > 0.01) {
        pixels.push({ x: dx, y: dy, color: rgbToHex(r, g, b), opacity: opacity * params.opacity });
      }
    }
  }
  return pixels;
}

/** Render a water droplet: teardrop shape with specular highlight */
function renderDroplet(
  size: number,
  color: string,
  params: BrushStyleParams,
  rng: () => number,
): BrushPixel[] {
  const pixels: BrushPixel[] = [];
  const halfSize = size / 2;
  const colorRGB = hexToRGB(color);
  const tailLen = params.tailLength;
  const tailAngleRad = (params.tailDirection * Math.PI) / 180;
  const tailDirX = Math.cos(tailAngleRad);
  const tailDirY = Math.sin(tailAngleRad);

  // The droplet extends in the opposite direction of the tail
  const bodyCX = -tailDirX * halfSize * tailLen * 0.3;
  const bodyCY = -tailDirY * halfSize * tailLen * 0.3;
  const bodyRadius = halfSize * (1 - tailLen * 0.2);

  for (let dy = -Math.ceil(halfSize * (1 + tailLen)); dy <= Math.ceil(halfSize * (1 + tailLen)); dy++) {
    for (let dx = -Math.ceil(halfSize * (1 + tailLen)); dx <= Math.ceil(halfSize * (1 + tailLen)); dx++) {
      // Distance from the circular body center
      const bx = dx - bodyCX;
      const by = dy - bodyCY;
      const bodyDist = Math.sqrt(bx * bx + by * by);

      // Distance along tail direction
      const alongTail = dx * tailDirX + dy * tailDirY;
      const perpTail = Math.abs(-dx * tailDirY + dy * tailDirX);

      // Tail shape: narrows as it extends along tail direction
      const tailWidth = bodyRadius * Math.max(0, 1 - alongTail / (halfSize * tailLen * 1.5));
      const inTail = alongTail > 0 && perpTail < tailWidth && alongTail < halfSize * tailLen * 1.5;

      const inBody = bodyDist <= bodyRadius;

      if (inBody || inTail) {
        // Shading
        const nx = dx / halfSize;
        const ny = dy / halfSize;
        const normalZ = Math.sqrt(Math.max(0, 1 - Math.min(1, nx * nx + ny * ny)));
        const shade = 0.5 + 0.5 * normalZ;

        // Highlight on opposite side of tail
        const hlNx = -tailDirX * 0.3;
        const hlNy = -tailDirY * 0.3;
        const distToHL = Math.sqrt((nx - hlNx) * (nx - hlNx) + (ny - hlNy) * (ny - hlNy));
        const specular = distToHL < 0.3 ? (1 - distToHL / 0.3) * 0.7 : 0;

        const r = Math.min(255, colorRGB.r * shade + specular * 200);
        const g = Math.min(255, colorRGB.g * shade + specular * 200);
        const b = Math.min(255, colorRGB.b * shade + specular * 200);

        // Edge softness
        let edgeDist: number;
        if (inBody) {
          edgeDist = bodyRadius - bodyDist;
        } else {
          edgeDist = tailWidth - perpTail;
        }
        const softEdge = 1 - params.hardness;
        const edgeWidth = Math.max(0.01, softEdge * halfSize * 0.3);
        const opacity = edgeDist < edgeWidth ? edgeDist / edgeWidth : 1;

        if (opacity > 0.01) {
          pixels.push({ x: dx, y: dy, color: rgbToHex(r, g, b), opacity: opacity * params.opacity });
        }
      }
    }
  }
  return pixels;
}

/** Render a soap bubble: thin membrane with rainbow iridescence and reflection */
function renderBubble(
  size: number,
  color: string,
  params: BrushStyleParams,
  rng: () => number,
): BrushPixel[] {
  const pixels: BrushPixel[] = [];
  const halfSize = size / 2;
  const colorRGB = hexToRGB(color);
  const iridescence = params.iridescence;
  const membrane = params.membraneThickness;
  const reflectionSz = params.reflectionSize;

  for (let dy = -Math.ceil(halfSize); dy <= Math.ceil(halfSize); dy++) {
    for (let dx = -Math.ceil(halfSize); dx <= Math.ceil(halfSize); dx++) {
      const dist = Math.sqrt(dx * dx + dy * dy);
      if (dist > halfSize + 0.5) continue;

      const nx = dx / halfSize;
      const ny = dy / halfSize;
      const normalizedDist = dist / halfSize;

      if (normalizedDist > 1) {
        // Anti-alias
        const a = 1 - (normalizedDist - 1);
        if (a > 0.01) pixels.push({ x: dx, y: dy, color: rgbToHex(colorRGB.r, colorRGB.g, colorRGB.b), opacity: a * 0.2 * params.opacity });
        continue;
      }

      const normalZ = Math.sqrt(Math.max(0, 1 - nx * nx - ny * ny));

      // Membrane: brighter at edges (Fresnel effect)
      const fresnel = 1 - normalZ;
      const membraneFactor = normalizedDist > (1 - membrane) ? 1 : fresnel * 0.5;

      // Rainbow iridescence based on angle and thickness variation
      let iridescentR = 0, iridescentG = 0, iridescentB = 0;
      if (iridescence > 0) {
        const angle = Math.atan2(ny, nx);
        const phase = angle * 3 + normalizedDist * 5 + rng() * 0.1;
        iridescentR = Math.sin(phase) * 0.5 + 0.5;
        iridescentG = Math.sin(phase + 2.094) * 0.5 + 0.5;
        iridescentB = Math.sin(phase + 4.189) * 0.5 + 0.5;
      }

      // Base color mixed with iridescence
      const baseR = colorRGB.r * (1 - iridescence * 0.5) + iridescentR * 255 * iridescence * 0.5;
      const baseG = colorRGB.g * (1 - iridescence * 0.5) + iridescentG * 255 * iridescence * 0.5;
      const baseB = colorRGB.b * (1 - iridescence * 0.5) + iridescentB * 255 * iridescence * 0.5;

      // Membrane brightness boost
      const brightness = 0.3 + membraneFactor * 0.7;

      // Reflection highlight (top-left area)
      const reflCX = -0.35, reflCY = -0.35;
      const distToRef = Math.sqrt((nx - reflCX) * (nx - reflCX) + (ny - reflCY) * (ny - reflCY));
      const reflection = distToRef < reflectionSz ? (1 - distToRef / reflectionSz) * 0.9 : 0;

      const r = Math.min(255, baseR * brightness + reflection * 255);
      const g = Math.min(255, baseG * brightness + reflection * 255);
      const b = Math.min(255, baseB * brightness + reflection * 255);

      // Transparency: bubbles are see-through
      const alpha = (0.2 + membraneFactor * 0.5 + reflection * 0.3) * params.opacity;

      if (alpha > 0.01) {
        pixels.push({ x: dx, y: dy, color: rgbToHex(r, g, b), opacity: alpha });
      }
    }
  }
  return pixels;
}

/** Render a cartoon punctuation mark */
function renderPunctuation(
  size: number,
  color: string,
  params: BrushStyleParams,
  rng: () => number,
): BrushPixel[] {
  const pixels: BrushPixel[] = [];
  const halfSize = size / 2;
  const colorRGB = hexToRGB(color);
  const outlineRGB = hexToRGB(params.outlineColor);
  const ptype = params.punctuationType;
  const outlineT = params.outlineThickness;

  const setPixel = (x: number, y: number, fill: boolean) => {
    if (outlineT > 0) {
      // Draw outline around the fill pixel
      for (let oy = -outlineT; oy <= outlineT; oy++) {
        for (let ox = -outlineT; ox <= outlineT; ox++) {
          if (ox === 0 && oy === 0) continue;
          const px = x + ox, py = y + oy;
          if (Math.abs(ox) + Math.abs(oy) <= outlineT + 1) {
            pixels.push({ x: px, y: py, color: rgbToHex(outlineRGB.r, outlineRGB.g, outlineRGB.b), opacity: params.opacity });
          }
        }
      }
    }
    if (fill) {
      pixels.push({ x, y, color: rgbToHex(colorRGB.r, colorRGB.g, colorRGB.b), opacity: params.opacity });
    }
  };

  const r = Math.max(1, Math.floor(halfSize * 0.35)); // dot radius

  if (ptype === 'exclamation') {
    // Tall bar + dot
    const barW = Math.max(1, Math.floor(halfSize * 0.3));
    const barH = Math.floor(halfSize * 1.2);
    for (let y = -barH; y <= -r * 2; y++) {
      for (let x = -barW; x <= barW; x++) {
        setPixel(x, y, true);
      }
    }
    // Dot
    for (let dy = -r; dy <= r; dy++) {
      for (let dx = -r; dx <= r; dx++) {
        if (dx * dx + dy * dy <= r * r) setPixel(dx, Math.floor(halfSize * 0.6) + dy, true);
      }
    }
  } else if (ptype === 'question') {
    // Curved top + dot
    const curveR = Math.floor(halfSize * 0.6);
    for (let a = 0; a < Math.PI * 1.5; a += 0.1) {
      const cx = Math.round(Math.cos(a) * curveR);
      const cy = Math.round(-Math.sin(a) * curveR) - Math.floor(halfSize * 0.3);
      for (let t = -1; t <= 1; t++) {
        setPixel(cx + t, cy, true);
        setPixel(cx, cy + t, true);
      }
    }
    // Stem
    const stemX = Math.round(curveR * 0.3);
    for (let y = -Math.floor(halfSize * 0.1); y <= Math.floor(halfSize * 0.15); y++) {
      setPixel(stemX, y, true);
    }
    // Dot
    for (let dy = -r; dy <= r; dy++) {
      for (let dx = -r; dx <= r; dx++) {
        if (dx * dx + dy * dy <= r * r) setPixel(dx, Math.floor(halfSize * 0.55) + dy, true);
      }
    }
  } else if (ptype === 'ellipsis') {
    // Three dots
    const spacing = Math.max(r * 2, Math.floor(halfSize * 0.5));
    for (const offsetX of [-spacing, 0, spacing]) {
      for (let dy = -r; dy <= r; dy++) {
        for (let dx = -r; dx <= r; dx++) {
          if (dx * dx + dy * dy <= r * r) setPixel(offsetX + dx, Math.floor(halfSize * 0.3) + dy, true);
        }
      }
    }
  } else if (ptype === 'comma') {
    // Small dot + curved tail
    for (let dy = -r; dy <= r; dy++) {
      for (let dx = -r; dx <= r; dx++) {
        if (dx * dx + dy * dy <= r * r) setPixel(dx, dy, true);
      }
    }
    // Tail curving down-left
    for (let i = 0; i < r * 2; i++) {
      const tx = -Math.floor(i * 0.4);
      const ty = r + i;
      setPixel(tx, ty, true);
    }
  } else if (ptype === 'period') {
    // Single dot
    for (let dy = -r; dy <= r; dy++) {
      for (let dx = -r; dx <= r; dx++) {
        if (dx * dx + dy * dy <= r * r) setPixel(dx, Math.floor(halfSize * 0.3) + dy, true);
      }
    }
  } else if (ptype === 'interrobang') {
    // Combination of ! and ?
    const curveR = Math.floor(halfSize * 0.5);
    for (let a = 0; a < Math.PI * 1.3; a += 0.12) {
      const cx = Math.round(Math.cos(a) * curveR);
      const cy = Math.round(-Math.sin(a) * curveR) - Math.floor(halfSize * 0.4);
      for (let t = 0; t <= 1; t++) {
        setPixel(cx + t, cy, true);
        setPixel(cx, cy + t, true);
      }
    }
    // Short stem
    const stemX = Math.round(curveR * 0.2);
    for (let y = 0; y <= Math.floor(halfSize * 0.15); y++) {
      setPixel(stemX, y, true);
    }
    // Dot
    for (let dy = -r; dy <= r; dy++) {
      for (let dx = -r; dx <= r; dx++) {
        if (dx * dx + dy * dy <= r * r) setPixel(dx, Math.floor(halfSize * 0.5) + dy, true);
      }
    }
  }
  return pixels;
}

/** Render a pixel emoji face */
function renderEmoji(
  size: number,
  color: string,
  params: BrushStyleParams,
  rng: () => number,
): BrushPixel[] {
  const pixels: BrushPixel[] = [];
  const halfSize = size / 2;
  const faceRGB = hexToRGB(color);
  const eyeRGB = hexToRGB('#000000');
  const mouthRGB = hexToRGB('#000000');
  const cheekRGB = hexToRGB('#ff6b6b');
  const etype = params.emojiType;
  const eyeSz = params.eyeSize;
  const mouthCrv = params.mouthCurve;

  // Draw face circle with sphere-like shading
  for (let dy = -Math.ceil(halfSize); dy <= Math.ceil(halfSize); dy++) {
    for (let dx = -Math.ceil(halfSize); dx <= Math.ceil(halfSize); dx++) {
      const dist = Math.sqrt(dx * dx + dy * dy);
      if (dist > halfSize) continue;

      const nx = dx / halfSize;
      const ny = dy / halfSize;
      const normalZ = Math.sqrt(Math.max(0, 1 - nx * nx - ny * ny));
      const shade = 0.7 + 0.3 * normalZ;

      const r = Math.min(255, faceRGB.r * shade);
      const g = Math.min(255, faceRGB.g * shade);
      const b = Math.min(255, faceRGB.b * shade);

      const edgeDist = halfSize - dist;
      const softEdge = 1 - params.hardness;
      const edgeWidth = Math.max(0.01, softEdge * halfSize);
      const opacity = edgeDist < edgeWidth ? edgeDist / edgeWidth : 1;

      if (opacity > 0.01) {
        pixels.push({ x: dx, y: dy, color: rgbToHex(r, g, b), opacity: opacity * params.opacity });
      }
    }
  }

  // Eye positions
  const eyeR = Math.max(1, Math.floor(halfSize * eyeSz));
  const eyeOffX = Math.floor(halfSize * 0.3);
  const eyeOffY = Math.floor(halfSize * 0.15);

  const drawEye = (cx: number, cy: number, isWink: boolean = false) => {
    if (isWink) {
      // Wink: horizontal line
      for (let dx = -eyeR; dx <= eyeR; dx++) {
        pixels.push({ x: cx + dx, y: cy, color: rgbToHex(eyeRGB.r, eyeRGB.g, eyeRGB.b), opacity: params.opacity });
      }
    } else if (etype === 'cool') {
      // Sunglasses: rectangular
      for (let dy = -eyeR; dy <= eyeR; dy++) {
        for (let dx = -eyeR * 2; dx <= eyeR * 2; dx++) {
          pixels.push({ x: cx + dx, y: cy + dy, color: rgbToHex(30, 30, 60), opacity: params.opacity });
        }
      }
    } else if (etype === 'love') {
      // Heart eyes
      for (let dy = -eyeR * 1.5; dy <= eyeR; dy++) {
        for (let dx = -eyeR * 1.5; dx <= eyeR * 1.5; dx++) {
          const nx = dx / (eyeR * 1.5);
          const ny = -dy / (eyeR * 1.5);
          const yS = ny - 0.2;
          const x2 = nx * nx;
          const y2 = yS * yS;
          const val = Math.pow(x2 + y2 - 1, 3) - x2 * Math.pow(yS, 3);
          if (val <= 0) {
            pixels.push({ x: cx + dx, y: cy + dy, color: '#ff3366', opacity: params.opacity });
          }
        }
      }
    } else if (etype === 'surprised') {
      // Round open mouth as eyes (O shape)
      for (let dy = -eyeR; dy <= eyeR; dy++) {
        for (let dx = -eyeR; dx <= eyeR; dx++) {
          const d = Math.sqrt(dx * dx + dy * dy);
          if (d <= eyeR && d >= eyeR * 0.5) {
            pixels.push({ x: cx + dx, y: cy + dy, color: rgbToHex(eyeRGB.r, eyeRGB.g, eyeRGB.b), opacity: params.opacity });
          }
        }
      }
    } else {
      // Normal round eyes
      for (let dy = -eyeR; dy <= eyeR; dy++) {
        for (let dx = -eyeR; dx <= eyeR; dx++) {
          if (dx * dx + dy * dy <= eyeR * eyeR) {
            pixels.push({ x: cx + dx, y: cy + dy, color: rgbToHex(eyeRGB.r, eyeRGB.g, eyeRGB.b), opacity: params.opacity });
          }
        }
      }
      // Highlight in eye
      const hlR = Math.max(1, Math.floor(eyeR * 0.4));
      for (let dy = -hlR; dy <= hlR; dy++) {
        for (let dx = -hlR; dx <= hlR; dx++) {
          if (dx * dx + dy * dy <= hlR * hlR) {
            pixels.push({ x: cx + dx - Math.floor(eyeR * 0.2), y: cy + dy - Math.floor(eyeR * 0.2), color: '#ffffff', opacity: params.opacity });
          }
        }
      }
    }
  };

  // Draw eyes
  const isWinkLeft = etype === 'wink';
  drawEye(-eyeOffX, -eyeOffY, isWinkLeft);
  drawEye(eyeOffX, -eyeOffY, false);

  // Mouth
  const mouthY = Math.floor(halfSize * 0.4);
  const mouthW = Math.floor(halfSize * 0.4);
  if (etype === 'surprised') {
    // O-shaped mouth
    const mouthR = Math.max(1, Math.floor(halfSize * 0.2));
    for (let dy = -mouthR; dy <= mouthR; dy++) {
      for (let dx = -mouthR; dx <= mouthR; dx++) {
        const d = Math.sqrt(dx * dx + dy * dy);
        if (d <= mouthR && d >= mouthR * 0.5) {
          pixels.push({ x: dx, y: mouthY + dy, color: rgbToHex(mouthRGB.r, mouthRGB.g, mouthRGB.b), opacity: params.opacity });
        }
      }
    }
  } else if (etype === 'dizzy') {
    // Spiral mouth / wavy
    for (let i = -mouthW; i <= mouthW; i++) {
      const wave = Math.round(Math.sin(i * 0.8) * 1.5);
      pixels.push({ x: i, y: mouthY + wave, color: rgbToHex(mouthRGB.r, mouthRGB.g, mouthRGB.b), opacity: params.opacity });
    }
  } else {
    // Curved mouth: mouthCurve > 0 = smile, < 0 = frown
    for (let i = -mouthW; i <= mouthW; i++) {
      const t = i / mouthW; // -1 to 1
      const curve = mouthCrv * (1 - t * t) * halfSize * 0.2;
      pixels.push({ x: i, y: mouthY - Math.round(curve), color: rgbToHex(mouthRGB.r, mouthRGB.g, mouthRGB.b), opacity: params.opacity });
    }
  }

  // Angry eyebrows
  if (etype === 'angry') {
    const browLen = Math.floor(eyeR * 1.5);
    for (let i = 0; i < browLen; i++) {
      pixels.push({ x: -eyeOffX - eyeR + i, y: -eyeOffY - eyeR - 1 - Math.floor(i * 0.5), color: rgbToHex(eyeRGB.r, eyeRGB.g, eyeRGB.b), opacity: params.opacity });
      pixels.push({ x: eyeOffX + eyeR - i, y: -eyeOffY - eyeR - 1 - Math.floor(i * 0.5), color: rgbToHex(eyeRGB.r, eyeRGB.g, eyeRGB.b), opacity: params.opacity });
    }
  }

  // Cheek blush for happy/love/wink
  if (etype === 'happy' || etype === 'love' || etype === 'wink') {
    const cheekR = Math.max(1, Math.floor(halfSize * 0.12));
    const cheekY = Math.floor(halfSize * 0.2);
    for (const cheekX of [-Math.floor(halfSize * 0.5), Math.floor(halfSize * 0.5)]) {
      for (let dy = -cheekR; dy <= cheekR; dy++) {
        for (let dx = -cheekR; dx <= cheekR; dx++) {
          if (dx * dx + dy * dy <= cheekR * cheekR) {
            pixels.push({ x: cheekX + dx, y: cheekY + dy, color: rgbToHex(cheekRGB.r, cheekRGB.g, cheekRGB.b), opacity: 0.4 * params.opacity });
          }
        }
      }
    }
  }

  return pixels;
}

// ---- Stroke-Aware Style Renderers (V6) ----
// These take the full stroke path and return absolute-position pixels.

/** Render a tapered stroke: varies width along the path with tapering at both ends.
 *  For each sample point along the stroke, draws a cross-section perpendicular to
 *  the stroke tangent, with size modulated by the taper function. */
function renderTaperedStroke(
  points: { x: number; y: number }[],
  size: number,
  color: string,
  params: BrushStyleParams,
  rng: () => number,
): BrushPixel[] {
  if (points.length === 0) return [];
  if (points.length === 1) {
    // Single point: render a small dot at minimum taper size
    const stamp = renderSolid(Math.max(1, Math.round(size * params.minSizeRatio)), color, params);
    return stamp.map(p => ({ ...p, x: p.x + Math.round(points[0].x), y: p.y + Math.round(points[0].y) }));
  }

  const arcLengths = computeArcLengths(points);
  const totalLen = arcLengths[arcLengths.length - 1];
  if (totalLen < 0.5) {
    // Degenerate path: single dot
    const stamp = renderSolid(size, color, params);
    return stamp.map(p => ({ ...p, x: p.x + Math.round(points[0].x), y: p.y + Math.round(points[0].y) }));
  }

  const colorRGB = hexToRGB(color);
  const result: BrushPixel[] = [];
  // Use a map to deduplicate pixel positions (later pixels overwrite earlier)
  const pixelMap = new Map<string, { color: string; opacity: number }>();

  // Sample the stroke at sub-pixel intervals for smooth tapering
  const stepSize = 0.5; // sample every half pixel for smooth coverage
  const numSamples = Math.max(2, Math.ceil(totalLen / stepSize) + 1);

  for (let i = 0; i < numSamples; i++) {
    const t = i / (numSamples - 1);
    const { x, y, tangentAngle } = interpolatePoint(points, arcLengths, t);

    // Compute size at this position based on taper
    const sizeFactor = taperFactor(t, params.taperLength, params.taperCurve, params.minSizeRatio);
    const localSize = Math.max(1, size * sizeFactor);
    const halfSize = localSize / 2;

    // Perpendicular direction to the tangent
    const perpX = -Math.sin(tangentAngle);
    const perpY = Math.cos(tangentAngle);

    // Draw a cross-section line perpendicular to the stroke
    const numCrossPixels = Math.ceil(localSize);
    for (let j = 0; j < numCrossPixels; j++) {
      const offset = -halfSize + (j / Math.max(1, numCrossPixels - 1)) * localSize;
      const px = Math.round(x + perpX * offset);
      const py = Math.round(y + perpY * offset);

      // Distance from center of this cross-section
      const dist = Math.abs(offset);
      const maxDist = halfSize;

      // Hardness-based edge falloff
      const edgeDist = maxDist - dist;
      const softEdge = 1 - params.hardness;
      const edgeWidth = Math.max(0.01, softEdge * maxDist);
      const opacity = edgeDist < edgeWidth ? edgeDist / edgeWidth : 1;

      if (opacity > 0.01) {
        const key = `${px},${py}`;
        pixelMap.set(key, {
          color: rgbToHex(colorRGB.r, colorRGB.g, colorRGB.b),
          opacity: opacity * params.opacity,
        });
      }
    }
  }

  // Convert map to array
  for (const [key, val] of pixelMap) {
    const [xStr, yStr] = key.split(',');
    result.push({ x: parseInt(xStr), y: parseInt(yStr), color: val.color, opacity: val.opacity });
  }

  return result;
}

/** Render a pipe/tube stroke: cylindrical shading with a highlight stripe.
 *  The highlight appears on one side (relative to the stroke direction),
 *  creating a 3D tube illusion. */
function renderPipeStroke(
  points: { x: number; y: number }[],
  size: number,
  color: string,
  params: BrushStyleParams,
  rng: () => number,
): BrushPixel[] {
  if (points.length === 0) return [];
  if (points.length === 1) {
    // Single point: render a pipe cross-section
    const stamp = renderPipeCrossSection(size, color, params);
    return stamp.map(p => ({ ...p, x: p.x + Math.round(points[0].x), y: p.y + Math.round(points[0].y) }));
  }

  const arcLengths = computeArcLengths(points);
  const totalLen = arcLengths[arcLengths.length - 1];
  if (totalLen < 0.5) {
    const stamp = renderPipeCrossSection(size, color, params);
    return stamp.map(p => ({ ...p, x: p.x + Math.round(points[0].x), y: p.y + Math.round(points[0].y) }));
  }

  const colorRGB = hexToRGB(color);
  const result: BrushPixel[] = [];
  const pixelMap = new Map<string, { color: string; opacity: number }>();

  const stepSize = 0.5;
  const numSamples = Math.max(2, Math.ceil(totalLen / stepSize) + 1);

  for (let i = 0; i < numSamples; i++) {
    const t = i / (numSamples - 1);
    const { x, y, tangentAngle } = interpolatePoint(points, arcLengths, t);

    // Perpendicular direction
    const perpX = -Math.sin(tangentAngle);
    const perpY = Math.cos(tangentAngle);

    // Compute highlight offset based on highlightPosition
    // The highlight is on one side of the pipe; we need to determine
    // which side in world-space based on the position parameter
    let highlightOffset: number;
    switch (params.highlightPosition) {
      case 'top':    highlightOffset = -0.5; break; // towards negative perpendicular
      case 'bottom': highlightOffset =  0.5; break; // towards positive perpendicular
      case 'left':   highlightOffset = -0.5; break;
      case 'right':  highlightOffset =  0.5; break;
      default:       highlightOffset = -0.5; break;
    }

    // For left/right, use tangent direction instead
    let highlightDir: { x: number; y: number };
    if (params.highlightPosition === 'left' || params.highlightPosition === 'right') {
      highlightDir = { x: Math.cos(tangentAngle) * highlightOffset, y: Math.sin(tangentAngle) * highlightOffset };
    } else {
      highlightDir = { x: perpX * highlightOffset, y: perpY * highlightOffset };
    }

    const halfSize = size / 2;
    const numCrossPixels = Math.ceil(size);

    for (let j = 0; j < numCrossPixels; j++) {
      const offset = -halfSize + (j / Math.max(1, numCrossPixels - 1)) * size;
      const px = Math.round(x + perpX * offset);
      const py = Math.round(y + perpY * offset);

      // Distance from center of pipe
      const dist = Math.abs(offset);
      const maxDist = halfSize;

      // Cylindrical shading: darker at edges, lighter toward highlight
      const normalDist = dist / maxDist; // 0 at center, 1 at edge

      // Compute how close this pixel is to the highlight band
      // Highlight is at offset = highlightOffset * halfSize
      const highlightCenter = highlightOffset * halfSize;
      const distToHighlight = Math.abs(offset - highlightCenter);
      const highlightBand = halfSize * params.highlightSize;

      // Cylindrical base shading (Lambertian approximation)
      // Brighter on the side facing the "light", darker on the opposite
      const lightAngle = params.highlightPosition === 'left' || params.highlightPosition === 'right'
        ? tangentAngle
        : tangentAngle + Math.PI / 2;
      // Dot product of surface normal with light direction
      const normalAtOffset = offset / halfSize; // -1 to 1
      const lightDot = normalAtOffset * (-highlightOffset) / 0.5; // normalized
      const shadeFactor = 0.5 + 0.5 * lightDot; // 0 (dark) to 1 (lit)

      // Mix between base color (shaded) and highlight
      let shadeColor: RGB;
      if (distToHighlight < highlightBand) {
        // In the highlight zone
        const highlightT = 1 - distToHighlight / highlightBand;
        const highlightMix = highlightT * params.highlightIntensity;
        // Add white to the base shaded color
        const baseShade = {
          r: colorRGB.r * shadeFactor * (1 - params.wallShade) + colorRGB.r * shadeFactor * params.wallShade,
          g: colorRGB.g * shadeFactor * (1 - params.wallShade) + colorRGB.g * shadeFactor * params.wallShade,
          b: colorRGB.b * shadeFactor * (1 - params.wallShade) + colorRGB.b * shadeFactor * params.wallShade,
        };
        // Actually compute proper shaded base color
        const darkFactor = 1 - params.wallShade * (1 - shadeFactor);
        const shadedBase = {
          r: colorRGB.r * darkFactor,
          g: colorRGB.g * darkFactor,
          b: colorRGB.b * darkFactor,
        };
        shadeColor = lerpColor(shadedBase, { r: 255, g: 255, b: 255 }, highlightMix);
      } else {
        // Outside highlight zone — just cylindrical shading
        const darkFactor = 1 - params.wallShade * (1 - shadeFactor);
        shadeColor = {
          r: colorRGB.r * darkFactor,
          g: colorRGB.g * darkFactor,
          b: colorRGB.b * darkFactor,
        };
      }

      // Edge falloff
      const edgeDist = maxDist - dist;
      const softEdge = 1 - params.hardness;
      const edgeWidth = Math.max(0.01, softEdge * maxDist);
      const opacity = edgeDist < edgeWidth ? edgeDist / edgeWidth : 1;

      if (opacity > 0.01) {
        const key = `${px},${py}`;
        pixelMap.set(key, {
          color: rgbToHex(shadeColor.r, shadeColor.g, shadeColor.b),
          opacity: opacity * params.opacity,
        });
      }
    }
  }

  for (const [key, val] of pixelMap) {
    const [xStr, yStr] = key.split(',');
    result.push({ x: parseInt(xStr), y: parseInt(yStr), color: val.color, opacity: val.opacity });
  }

  return result;
}

/** Helper: render a single pipe cross-section (for single-point strokes) */
function renderPipeCrossSection(
  size: number,
  color: string,
  params: BrushStyleParams,
): BrushPixel[] {
  const pixels: BrushPixel[] = [];
  const halfSize = size / 2;
  const colorRGB = hexToRGB(color);

  for (let dy = -Math.ceil(halfSize); dy < Math.floor(halfSize + 0.5); dy++) {
    for (let dx = -Math.ceil(halfSize); dx < Math.floor(halfSize + 0.5); dx++) {
      const dist = Math.sqrt(dx * dx + dy * dy);
      const maxDist = halfSize;

      if (dist <= maxDist) {
        const normalDist = dist / maxDist;
        // Cylindrical shading: brighter toward the highlight side
        const shadeFactor = 1 - normalDist * params.wallShade;
        const shadeColor = {
          r: colorRGB.r * shadeFactor,
          g: colorRGB.g * shadeFactor,
          b: colorRGB.b * shadeFactor,
        };

        const edgeDist = maxDist - dist;
        const softEdge = 1 - params.hardness;
        const edgeWidth = Math.max(0.01, softEdge * maxDist);
        const opacity = edgeDist < edgeWidth ? edgeDist / edgeWidth : 1;

        if (opacity > 0.01) {
          pixels.push({
            x: dx, y: dy,
            color: rgbToHex(shadeColor.r, shadeColor.g, shadeColor.b),
            opacity: opacity * params.opacity,
          });
        }
      }
    }
  }

  return pixels;
}

/** Render a segmented pipe / bellows stroke: repeated segments with joints.
 *  Each segment is a short pipe section, and joints have wider bellows. */
function renderSegmentedPipeStroke(
  points: { x: number; y: number }[],
  size: number,
  color: string,
  params: BrushStyleParams,
  rng: () => number,
): BrushPixel[] {
  if (points.length === 0) return [];
  if (points.length === 1) {
    const stamp = renderPipeCrossSection(size, color, params);
    return stamp.map(p => ({ ...p, x: p.x + Math.round(points[0].x), y: p.y + Math.round(points[0].y) }));
  }

  const arcLengths = computeArcLengths(points);
  const totalLen = arcLengths[arcLengths.length - 1];
  if (totalLen < 0.5) {
    const stamp = renderPipeCrossSection(size, color, params);
    return stamp.map(p => ({ ...p, x: p.x + Math.round(points[0].x), y: p.y + Math.round(points[0].y) }));
  }

  const colorRGB = hexToRGB(color);
  const result: BrushPixel[] = [];
  const pixelMap = new Map<string, { color: string; opacity: number }>();

  const segmentLen = Math.max(2, params.segmentLength);
  const gapLen = Math.max(0, params.segmentGap);
  const cycleLen = segmentLen + gapLen; // total length of one segment + gap cycle

  const stepSize = 0.5;
  const numSamples = Math.max(2, Math.ceil(totalLen / stepSize) + 1);

  for (let i = 0; i < numSamples; i++) {
    const t = i / (numSamples - 1);
    const { x, y, tangentAngle } = interpolatePoint(points, arcLengths, t);

    // Position along the stroke in pixels
    const posAlongStroke = t * totalLen;

    // Determine where we are in the segment cycle
    const cyclePos = posAlongStroke % cycleLen;
    const isInGap = cyclePos >= segmentLen; // in the gap between segments
    const segmentLocalT = cyclePos / segmentLen; // 0-1 within the segment

    if (isInGap) continue; // Don't draw in gaps

    // Compute width at this position
    // Each segment tapers at its ends if segmentTaper > 0
    let widthFactor = 1;
    if (params.segmentTaper > 0) {
      // Taper at segment start and end
      const taperAtStart = Math.min(1, segmentLocalT / (params.segmentTaper * 0.5 + 0.01));
      const taperAtEnd = Math.min(1, (1 - segmentLocalT) / (params.segmentTaper * 0.5 + 0.01));
      widthFactor = Math.min(taperAtStart, taperAtEnd);
      widthFactor = 1 - params.segmentTaper * (1 - widthFactor);
    }

    // Bellows effect: widen at segment joints (start and end of segment)
    const jointProximity = Math.min(segmentLocalT, 1 - segmentLocalT);
    const bellowsFactor = 1 + params.bellowsWidth * Math.exp(-jointProximity * 10);

    const localSize = Math.max(1, size * widthFactor * bellowsFactor);
    const halfSize = localSize / 2;

    // Perpendicular direction
    const perpX = -Math.sin(tangentAngle);
    const perpY = Math.cos(tangentAngle);

    // Pipe-style cylindrical shading
    const highlightOffset = params.highlightPosition === 'bottom' || params.highlightPosition === 'right' ? 0.5 : -0.5;

    const numCrossPixels = Math.ceil(localSize);
    for (let j = 0; j < numCrossPixels; j++) {
      const offset = -halfSize + (j / Math.max(1, numCrossPixels - 1)) * localSize;
      const px = Math.round(x + perpX * offset);
      const py = Math.round(y + perpY * offset);

      const dist = Math.abs(offset);
      const maxDist = halfSize;
      const normalAtOffset = offset / maxDist;
      const lightDot = normalAtOffset * (-highlightOffset) / 0.5;
      const shadeFactor = 0.5 + 0.5 * lightDot;

      // Dark factor for pipe shading
      const darkFactor = 1 - params.wallShade * (1 - shadeFactor);

      // Joint highlighting — brighter at joints
      const jointBright = bellowsFactor > 1 ? (bellowsFactor - 1) * 0.3 : 0;
      const shadeColor = {
        r: Math.min(255, colorRGB.r * darkFactor * (1 + jointBright)),
        g: Math.min(255, colorRGB.g * darkFactor * (1 + jointBright)),
        b: Math.min(255, colorRGB.b * darkFactor * (1 + jointBright)),
      };

      const edgeDist = maxDist - dist;
      const softEdge = 1 - params.hardness;
      const edgeWidth = Math.max(0.01, softEdge * maxDist);
      const opacity = edgeDist < edgeWidth ? edgeDist / edgeWidth : 1;

      if (opacity > 0.01) {
        const key = `${px},${py}`;
        pixelMap.set(key, {
          color: rgbToHex(shadeColor.r, shadeColor.g, shadeColor.b),
          opacity: opacity * params.opacity,
        });
      }
    }
  }

  // Also draw joint rings (darker/raised ring at each segment boundary)
  // This adds a subtle ring at each segment start/end for the bellows look
  if (params.bellowsWidth > 0.1) {
    const numSegments = Math.ceil(totalLen / cycleLen);
    for (let seg = 0; seg <= numSegments; seg++) {
      const jointPos = seg * cycleLen;
      const jointT = jointPos / totalLen;
      if (jointT > 1) break;

      const { x, y, tangentAngle } = interpolatePoint(points, arcLengths, jointT);
      const perpX = -Math.sin(tangentAngle);
      const perpY = Math.cos(tangentAngle);

      const ringWidth = size * (1 + params.bellowsWidth * 0.5);
      const halfRing = ringWidth / 2;
      const numRingPixels = Math.ceil(ringWidth);

      for (let j = 0; j < numRingPixels; j++) {
        const offset = -halfRing + (j / Math.max(1, numRingPixels - 1)) * ringWidth;
        const px = Math.round(x + perpX * offset);
        const py = Math.round(y + perpY * offset);

        const dist = Math.abs(offset);
        const maxDist = halfRing;

        // Ring is a thin darker line
        const isEdge = dist > maxDist - 1.5 && dist <= maxDist;
        if (isEdge || dist <= 0.5) {
          const edgeDist = maxDist - dist;
          const softEdge = 1 - params.hardness;
          const edgeWidth = Math.max(0.01, softEdge * maxDist);
          const opacity = edgeDist < edgeWidth ? edgeDist / edgeWidth : 1;

          // Ring is slightly darker than the pipe color
          const ringColor = {
            r: colorRGB.r * 0.7,
            g: colorRGB.g * 0.7,
            b: colorRGB.b * 0.7,
          };

          if (opacity > 0.01) {
            const key = `${px},${py}`;
            pixelMap.set(key, {
              color: rgbToHex(ringColor.r, ringColor.g, ringColor.b),
              opacity: opacity * params.opacity * 0.6,
            });
          }
        }
      }
    }
  }

  for (const [key, val] of pixelMap) {
    const [xStr, yStr] = key.split(',');
    result.push({ x: parseInt(xStr), y: parseInt(yStr), color: val.color, opacity: val.opacity });
  }

  return result;
}

/** Render a vine / blood vessel stroke: organic shape with directional lighting
 *  and a darker vein center line. Edges have organic noise for a natural look. */
function renderVineStroke(
  points: { x: number; y: number }[],
  size: number,
  color: string,
  params: BrushStyleParams,
  rng: () => number,
): BrushPixel[] {
  if (points.length === 0) return [];
  if (points.length === 1) {
    const stamp = renderVineCrossSection(size, color, params, rng);
    return stamp.map(p => ({ ...p, x: p.x + Math.round(points[0].x), y: p.y + Math.round(points[0].y) }));
  }

  const arcLengths = computeArcLengths(points);
  const totalLen = arcLengths[arcLengths.length - 1];
  if (totalLen < 0.5) {
    const stamp = renderVineCrossSection(size, color, params, rng);
    return stamp.map(p => ({ ...p, x: p.x + Math.round(points[0].x), y: p.y + Math.round(points[0].y) }));
  }

  const colorRGB = hexToRGB(color);
  const veinRGB = hexToRGB(params.veinColor);
  const result: BrushPixel[] = [];
  const pixelMap = new Map<string, { color: string; opacity: number }>();

  // Light direction in radians
  const lightAngleRad = (params.lightDirection * Math.PI) / 180;
  const lightDirX = Math.cos(lightAngleRad);
  const lightDirY = Math.sin(lightAngleRad);

  const stepSize = 0.5;
  const numSamples = Math.max(2, Math.ceil(totalLen / stepSize) + 1);

  // Pre-generate noise offsets for organic edge variation
  const noiseOffsets: number[] = [];
  for (let i = 0; i < numSamples; i++) {
    noiseOffsets.push((rng() - 0.5) * 2 * params.organicNoise * size * 0.3);
  }

  for (let i = 0; i < numSamples; i++) {
    const t = i / (numSamples - 1);
    const { x, y, tangentAngle } = interpolatePoint(points, arcLengths, t);

    // Perpendicular direction
    const perpX = -Math.sin(tangentAngle);
    const perpY = Math.cos(tangentAngle);

    // Add organic noise to the width
    const noiseOffset = noiseOffsets[i] ?? 0;
    const localSize = Math.max(1, size + noiseOffset);
    const halfSize = localSize / 2;

    // Light direction projected onto the perpendicular axis
    // This determines which side of the vine is lit
    const lightPerpDot = perpX * lightDirX + perpY * lightDirY;
    // lightPerpDot > 0 means light comes from the positive perpendicular side

    const numCrossPixels = Math.ceil(localSize) + 2; // extra for noise
    for (let j = 0; j < numCrossPixels; j++) {
      const offset = -halfSize + (j / Math.max(1, numCrossPixels - 1)) * localSize;
      const px = Math.round(x + perpX * offset);
      const py = Math.round(y + perpY * offset);

      const dist = Math.abs(offset);
      const maxDist = halfSize;

      if (dist > maxDist + 0.5) continue; // outside the vine

      // Normalized distance from center (0 at center, 1 at edge)
      const normalDist = dist / maxDist;

      // Lighting: based on the dot product of the surface normal with the light direction
      // Surface normal at this offset points in the perpendicular direction scaled by sign(offset)
      const surfaceNormalSign = offset >= 0 ? 1 : -1;
      const lightOnThisSide = lightPerpDot * surfaceNormalSign;
      // lightOnThisSide > 0 means light hits this side directly

      // Shade factor: brighter where light hits, darker on shadow side
      const shadeFactor = 1 - params.lightIntensity * (1 - Math.max(0, lightOnThisSide));
      // Also darken slightly toward edges (subsurface scattering approximation)
      const edgeDarken = 1 - normalDist * 0.2 * params.lightIntensity;

      // Vein center line: darker line running through the middle
      const veinWidth = 0.15; // fraction of total width for the vein
      const veinMix = normalDist < veinWidth
        ? 1 - (normalDist / veinWidth) * 0.7
        : 0;

      // Compute final color
      const litBase = {
        r: colorRGB.r * shadeFactor * edgeDarken,
        g: colorRGB.g * shadeFactor * edgeDarken,
        b: colorRGB.b * shadeFactor * edgeDarken,
      };
      const finalColor = lerpColor(litBase, veinRGB, veinMix * 0.6);

      // Edge falloff with organic softness
      const edgeDist = maxDist - dist;
      const softEdge = 1 - params.hardness;
      const edgeWidth = Math.max(0.01, softEdge * maxDist);
      const opacity = edgeDist < edgeWidth ? edgeDist / edgeWidth : 1;

      if (opacity > 0.01) {
        const key = `${px},${py}`;
        pixelMap.set(key, {
          color: rgbToHex(finalColor.r, finalColor.g, finalColor.b),
          opacity: opacity * params.opacity,
        });
      }
    }
  }

  // Add sub-branches if branchDensity > 0
  if (params.branchDensity > 0.05) {
    const numBranches = Math.max(0, Math.floor(totalLen * params.branchDensity * 0.1));
    for (let b = 0; b < numBranches; b++) {
      const branchT = rng();
      const { x, y, tangentAngle } = interpolatePoint(points, arcLengths, branchT);

      // Branch angle: perpendicular to the main vine + some random variation
      const branchAngle = tangentAngle + (rng() > 0.5 ? Math.PI / 2 : -Math.PI / 2) + (rng() - 0.5) * 0.5;
      const branchLength = Math.max(2, size * (0.5 + rng() * 1.5));
      const branchSize = Math.max(1, Math.round(size * 0.4));

      // Draw a short line for the branch
      const steps = Math.ceil(branchLength);
      for (let s = 0; s < steps; s++) {
        const frac = s / steps;
        const bx = Math.round(x + Math.cos(branchAngle) * s);
        const by = Math.round(y + Math.sin(branchAngle) * s);

        // Branch also tapers
        const taperFrac = 1 - frac * 0.5;
        const bHalfSize = Math.max(0.5, branchSize * taperFrac / 2);

        for (let dy = -Math.ceil(bHalfSize); dy <= Math.ceil(bHalfSize); dy++) {
          for (let dx = -Math.ceil(bHalfSize); dx <= Math.ceil(bHalfSize); dx++) {
            if (dx * dx + dy * dy <= bHalfSize * bHalfSize) {
              const branchColor = lerpColor(colorRGB, veinRGB, 0.3);
              const bOpacity = (1 - frac * 0.7) * params.opacity * 0.8;
              if (bOpacity > 0.01) {
                const key = `${bx + dx},${by + dy}`;
                if (!pixelMap.has(key)) {
                  pixelMap.set(key, {
                    color: rgbToHex(branchColor.r, branchColor.g, branchColor.b),
                    opacity: bOpacity,
                  });
                }
              }
            }
          }
        }
      }
    }
  }

  for (const [key, val] of pixelMap) {
    const [xStr, yStr] = key.split(',');
    result.push({ x: parseInt(xStr), y: parseInt(yStr), color: val.color, opacity: val.opacity });
  }

  return result;
}

/** Helper: render a single vine cross-section (for single-point strokes) */
function renderVineCrossSection(
  size: number,
  color: string,
  params: BrushStyleParams,
  rng: () => number,
): BrushPixel[] {
  const pixels: BrushPixel[] = [];
  const halfSize = size / 2;
  const colorRGB = hexToRGB(color);
  const veinRGB = hexToRGB(params.veinColor);

  // Simple circular vine cross-section with vein center
  for (let dy = -Math.ceil(halfSize); dy < Math.floor(halfSize + 0.5); dy++) {
    for (let dx = -Math.ceil(halfSize); dx < Math.floor(halfSize + 0.5); dx++) {
      const dist = Math.sqrt(dx * dx + dy * dy);
      const maxDist = halfSize;

      if (dist <= maxDist) {
        const normalDist = dist / maxDist;
        const veinMix = normalDist < 0.15 ? 1 - normalDist / 0.15 * 0.7 : 0;
        const shadeColor = lerpColor(colorRGB, veinRGB, veinMix * 0.6);

        const edgeDist = maxDist - dist;
        const softEdge = 1 - params.hardness;
        const edgeWidth = Math.max(0.01, softEdge * maxDist);
        const opacity = edgeDist < edgeWidth ? edgeDist / edgeWidth : 1;

        if (opacity > 0.01) {
          pixels.push({
            x: dx, y: dy,
            color: rgbToHex(shadeColor.r, shadeColor.g, shadeColor.b),
            opacity: opacity * params.opacity,
          });
        }
      }
    }
  }

  return pixels;
}

