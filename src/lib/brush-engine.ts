/** Generate the pixel stamp for a brush at a single point.
 *  For stamp-based styles, this is the full rendering.
 *  For stroke-aware styles, this returns a simplified preview stamp
 *  (use generateStrokePixels for correct full-stroke rendering). */
export function generateBrushStamp(
  style: BrushStyleType,
  size: number,
  color: string,
  params: Partial<BrushStyleParams> | undefined,
  /** Per-stamp seed for deterministic randomness (e.g. point index * 7919) */
  stampSeed: number = 0,
): BrushPixel[] {
  const p: BrushStyleParams = { ...DEFAULT_BRUSH_STYLE, ...params };
  const rng = mulberry32(p.seed + stampSeed);

  switch (style) {
    case 'solid':
      return renderSolid(size, color, p);
    case 'glow_orb':
      return renderGlowOrb(size, color, p, rng);
    case 'dual_flame':
      return renderDualFlame(size, color, p, rng);
    case 'spray':
      return renderSpray(size, color, p, rng);
    case 'neon':
      return renderNeon(size, color, p, rng);
    case 'gradient':
      return renderGradient(size, color, p, rng);
    case 'scatter':
      return renderScatter(size, color, p, rng);
    // V8: Shape stamp styles
    case 'star':
      return renderStar(size, color, p, rng);
    case 'heart':
      return renderHeart(size, color, p, rng);
    case 'sphere':
      return renderSphere(size, color, p, rng);
    case 'droplet':
      return renderDroplet(size, color, p, rng);
    case 'bubble':
      return renderBubble(size, color, p, rng);
    case 'punctuation':
      return renderPunctuation(size, color, p, rng);
    case 'emoji':
      return renderEmoji(size, color, p, rng);
    // Stroke-aware styles: simplified stamp preview for live drawing
    case 'tapered':
      // Preview: render as solid with size reduced slightly (approximation)
      return renderSolid(Math.max(1, Math.round(size * 0.8)), color, p);
    case 'pipe':
      return renderPipeCrossSection(size, color, p);
    case 'segmented_pipe':
      return renderPipeCrossSection(size, color, p);
    case 'vine':
      return renderVineCrossSection(size, color, p, rng);
    // V9: Industrial/mechanical styles
    case 'bevel_seam':
      return renderBevelSeamCrossSection(size, color, p);
    case 'prism':
      return renderPrismCrossSection(size, color, p);
    case 'plate':
      return renderPlateCrossSection(size, color, p, rng);
    case 'grille':
      return renderGrilleCrossSection(size, color, p, rng);
    case 'vent':
      return renderVentCrossSection(size, color, p, rng);
    default:
      return renderSolid(size, color, p);
  }
}

/** Generate pixels for a complete stroke (stroke-aware rendering).
 *  This is the correct way to render tapered, pipe, segmented_pipe, and vine styles.
 *  For stamp-based styles, this falls back to per-point stamp rendering.
 *  Returns absolute-position pixels. */
export function generateStrokePixels(
  style: BrushStyleType,
  points: { x: number; y: number }[],
  size: number,
  color: string,
  params: Partial<BrushStyleParams> | undefined,
  seed: number = 0,
): BrushPixel[] {
  const p: BrushStyleParams = { ...DEFAULT_BRUSH_STYLE, ...params };
  const rng = mulberry32(p.seed + seed);

  switch (style) {
    case 'tapered':
      return renderTaperedStroke(points, size, color, p, rng);
    case 'pipe':
      return renderPipeStroke(points, size, color, p, rng);
    case 'segmented_pipe':
      return renderSegmentedPipeStroke(points, size, color, p, rng);
    case 'vine':
      return renderVineStroke(points, size, color, p, rng);
    // V9: Industrial/mechanical styles
    case 'bevel_seam':
      return renderBevelSeamStroke(points, size, color, p, rng);
    case 'prism':
      return renderPrismStroke(points, size, color, p, rng);
    case 'plate':
      return renderPlateStroke(points, size, color, p, rng);
    case 'grille':
      return renderGrilleStroke(points, size, color, p, rng);
    case 'vent':
      return renderVentStroke(points, size, color, p, rng);
    default:
      // Stamp-based styles: fall back to per-point rendering
      return renderStampBasedStroke(style, points, size, color, p, rng);
  }
}

/** Fallback for stamp-based styles when called via generateStrokePixels */
function renderStampBasedStroke(
  style: BrushStyleType,
  points: { x: number; y: number }[],
  size: number,
  color: string,
  params: BrushStyleParams,
  rng: () => number,
): BrushPixel[] {
  const result: BrushPixel[] = [];
  for (let i = 0; i < points.length; i++) {
    const pt = points[i];
    const stamp = generateBrushStamp(style, size, color, params, i * 7919);
    for (const sp of stamp) {
      result.push({
        x: sp.x + Math.round(pt.x),
        y: sp.y + Math.round(pt.y),
        color: sp.color,
        opacity: sp.opacity,
      });
    }
  }
  return result;
}

/** Apply a brush stamp to a PixelGrid, respecting opacity blending.
 *  Modifies `pixels` in-place and returns it. */
export function applyBrushStamp(
  pixels: PixelColor[][],
  stamp: BrushPixel[],
  centerX: number,
  centerY: number,
  width: number,
  height: number,
): PixelColor[][] {
  for (const sp of stamp) {
    const tx = centerX + sp.x;
    const ty = centerY + sp.y;
    if (tx >= 0 && tx < width && ty >= 0 && ty < height) {
      const existing = pixels[ty][tx];
      pixels[ty][tx] = blendWithBackground(existing, hexToRGB(sp.color), sp.opacity);
    }
  }
  return pixels;
}

/** Apply stroke-aware pixels (absolute positions) to a PixelGrid. */
export function applyStrokePixels(
  pixels: PixelColor[][],
  strokePixels: BrushPixel[],
  width: number,
  height: number,
): PixelColor[][] {
  for (const sp of strokePixels) {
    // For stroke-aware pixels, x and y are absolute coordinates
    const tx = sp.x;
    const ty = sp.y;
    if (tx >= 0 && tx < width && ty >= 0 && ty < height) {
      const existing = pixels[ty][tx];
      pixels[ty][tx] = blendWithBackground(existing, hexToRGB(sp.color), sp.opacity);
    }
  }
  return pixels;
}

